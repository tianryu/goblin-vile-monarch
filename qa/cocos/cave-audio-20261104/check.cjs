const assert = require('node:assert/strict');
const { GameModel } = require('./model/GameModel.js');
const { ChapterDirector } = require('./model/ChapterDirector.js');
const { CAVE_FORGE_X } = require('./model/BaseLayout.js');

const fresh = new GameModel();
const old = fresh.snapshot();
old.revision = 17;
const oldForge = old.buildings.find(b => b.kind === 'forge');
oldForge.x = 2705;
oldForge.job = { left: 7, total: 16, next: 1 };
oldForge.stock = 2;
old.gearStock = 5;
const migrated = new GameModel(old);
assert.equal(migrated.forge.x, CAVE_FORGE_X);
assert.equal(migrated.forge.id, oldForge.id);
assert.equal(migrated.forge.job.left, 7);
assert.equal(migrated.forge.stock, 2);
assert.equal(migrated.state.gearStock, 5);
assert.equal(new GameModel(migrated.snapshot()).forge.x, CAVE_FORGE_X);
migrated.finishJob(migrated.forge);
assert.ok(migrated.events.some(e => e.kind === 'build' && e.x === CAVE_FORGE_X));

const game = new GameModel();
const s = game.state;
const progress = s.chapter;
Object.assign(progress.seen, { opening: true, towerReady: true, expedition: true, hidden: true });
progress.seen['facility:forge'] = true;
Object.assign(progress.done, { hammer: true, bow: true, wall: true, tower: true });
const guide = new ChapterDirector(game, () => {});
const read = () => { s.elapsed += .25; guide.update(.25); return guide.guide; };
const gear = s.buildings.find(b => b.kind === 'gear');
s.player.x = gear.x;
assert.notEqual(read()?.key, 'facility:gear');
assert.equal(progress.seen['facility:gear'], undefined);
s.gearStock = 1;
assert.equal(read()?.action, 'scrapGear');
s.gearStock = 0;
assert.notEqual(read()?.key, 'facility:gear');
s.player.x = game.hall.x - 240;
for (const kind of ['wall','tower','farm']) {
    const b = s.buildings.find(b => b.kind === kind && b.region === -1);
    b.level = 1; b.hp = b.maxHp = 100;
}
while (s.goblins.length < 10) s.goblins.push(game.makeGoblin('idle', 0));
s.day = 6;
assert.notEqual(read()?.key, 'hall');
s.goblins.push(game.makeGoblin('idle', 0));
s.day = 5;
assert.notEqual(read()?.key, 'hall');
s.day = 6;
const wall = s.buildings.find(b => b.kind === 'wall' && b.region === -1);
wall.hp = 0;
assert.notEqual(read()?.key, 'hall');
wall.hp = 100;
game.hall.level = 2;
assert.notEqual(read()?.key, 'hall');
game.hall.level = 1;
const hallHint = read();
assert.equal(hallHint.key, 'hall');
assert.equal(hallHint.target.id, game.hall.id);
assert.equal(hallHint.action, undefined);
assert.equal(game.pauses.size, 0);
s.elapsed += 9;
assert.notEqual(read()?.key, 'hall');

const tower = s.buildings.find(b => b.kind === 'tower' && b.region === -1);
const hunter = game.makeGoblin('hunter', tower.x);
hunter.towerId = tower.id;
hunter.task = 'tower';
s.goblins = [hunter];
s.enemies = [];
game.rebuildEnemyCache();
const deer = { id:game.id(),kind:'deer',x:tower.x+400,home:tower.x+400,hp:3,face:1,moving:false,timer:0 };
s.animals = [deer];
game.updateGoblins(1/30);
const shot = s.shots.find(a=>a.targetId===deer.id);
assert.ok(shot && shot.fromY > 100 && shot.targetY === 32);
game.updateShots(shot.duration);
assert.ok(deer.hp <= 0);
assert.ok(s.coins.some(c=>c.x===deer.x));
hunter.cooldown = 0;
s.shots = [];
const outOfRange = {...deer,id:game.id(),hp:3,x:tower.x+466};
s.animals = [outOfRange];
game.updateGoblins(1/30);
assert.ok(!s.shots.length);

const newGame = new GameModel();
const stamina = newGame.state.player;
stamina.stamina = 0; stamina.exhausted = true;
const video = { key:'hudAd:stamina', type:'ad', targetId:-200, variant:'stamina', icon:'icon_play', cost:0 };
assert.equal(newGame.act(video), 'ad');
assert.equal(newGame.infiniteStaminaSeconds, 0);
assert.equal(newGame.grantAdReward('stamina',''), false);
assert.equal(newGame.grantAdReward('stamina','isolated-receipt-1'), true);
assert.equal(newGame.infiniteStaminaSeconds, 600);
assert.equal(newGame.grantAdReward('stamina','isolated-receipt-1'), false);
newGame.input = { axis: 1, run: true };
newGame.tick(.1);
assert.equal(stamina.stamina, 100);
assert.ok(stamina.x > 23 && stamina.x < 28, 'stamina does not add a speed bonus');
assert.equal(new GameModel(newGame.snapshot()).infiniteStaminaSeconds, newGame.infiniteStaminaSeconds);
newGame.pause('test', true);
const paused = newGame.infiniteStaminaSeconds;
newGame.tick(.1);
assert.equal(newGame.infiniteStaminaSeconds, paused);
newGame.pause('test', false);
assert.equal(newGame.grantAdReward('stamina','isolated-receipt-2'), true);
assert.equal(newGame.infiniteStaminaSeconds, paused + 600);
newGame.state.infiniteStaminaUntil = newGame.state.elapsed + .05;
newGame.input = { axis: 1, run: true };
newGame.tick(.1);
assert.equal(newGame.infiniteStaminaSeconds, 0);
assert.ok(stamina.stamina < 100);
console.log('PASS: forge migration, optional hall and loot guidance, tower hunting, stamina receipt validation, persistence, pause and expiry');
